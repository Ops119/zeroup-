// Writes ABIs and bytecode from Hardhat artifacts into a typed TS module.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const contracts = {
  ZeroupPool: "contracts/ZeroupPool.sol/ZeroupPool.json",
  MockUSDC: "contracts/MockUSDC.sol/MockUSDC.json",
  Screener: "contracts/Screener.sol/Screener.json",
  Groth16Verifier: "contracts/Groth16Verifier.sol/Groth16Verifier.json",
  PoseidonT3: "contracts/lib/PoseidonT3.sol/PoseidonT3.json",
};

let out = "// Generated by scripts/export-abis.js. Do not edit.\n\n";
for (const [name, rel] of Object.entries(contracts)) {
  const a = JSON.parse(fs.readFileSync(path.join(root, "artifacts", rel), "utf8"));
  out += `export const ${name} = {\n`;
  out += `  abi: ${JSON.stringify(a.abi)} as const,\n`;
  out += `  bytecode: ${JSON.stringify(a.bytecode)} as \`0x\${string}\`,\n`;
  out += `  linkReferences: ${JSON.stringify(a.linkReferences)} as Record<string, Record<string, { start: number; length: number }[]>>,\n`;
  out += `};\n\n`;
}
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src/generated/contracts.ts"), out);
console.log("wrote src/generated/contracts.ts");
